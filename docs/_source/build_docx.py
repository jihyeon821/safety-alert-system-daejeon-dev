def ms_rows():
    rows = []
    for m in P.MILESTONES:
        fin = max(P.SCHEDULE[x]["finish"] for x in m[2]).isoformat()
        rows.append([m[0], m[1], fin if m[3] else f"[가정] {fin}", "달성" if m[3] else "계획"])
    return rows


def top_risks(n=6):
    rs = sorted(P.RISKS, key=lambda k: -k[5] * k[6])[:n]
    return [[k[0], k[2], f"{k[5]}×{k[6]}={k[5] * k[6]}", k[7], k[8]] for k in rs]


def save(doc: Doc, group: str, name: str):
    path = OUT / FOLDER[group] / name
    doc.save(path)
    return path


